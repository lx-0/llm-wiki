import { describe, expect, it } from 'vitest';
import { parseDoctor } from '../vault/doctor';
import { parseMenu } from '../vault/menu';
import { ACTION_SCHEMA } from './actions';
import {
  doctorSchema,
  fieldInventoryDrift,
  menuSchema,
  readRepoJson,
  validateDoctor,
  validateMenu,
} from './contract';

// The engine's oracle goldens: its real `menu --json` / `doctor --quick --json` output on the
// fixture vault (tests/golden/oracle/), which pytest validates against the same schema files.
const menuGolden = <T = unknown>() => readRepoJson<T>('tests/golden/oracle/menu.json');
const doctorGolden = <T = unknown>() => readRepoJson<T>('tests/golden/oracle/doctor-quick.json');

// The payload fields the app knows — read or deliberately ignored. A field the engine adds
// to a schema fails `fieldInventoryDrift` until someone decides here what the app does with it.
const KNOWN_FIELDS: Record<string, string[]> = {
  StatusJSON: ['articles', 'last_compile_ago', 'ollama_reachable'], // MenuResult.status, verbatim
  // read: all but `key` (the TUI's menu number)
  SuggestionJSON: ['id', 'title', 'verb', 'group', 'argv', 'count', 'label', 'priority', 'key'],
  ActionJSON: ['id', 'title', 'verb', 'group', 'argv'], // tools, read in full
  // read: id, severity, message, title, verb, fix, dispatch_args; ignored: category, details
  CheckJSON: ['id', 'category', 'severity', 'message', 'fix', 'dispatch_args', 'details', 'title', 'verb'],
};

describe('the schema-2 contract (docs/contracts, generated by scripts/core/contracts.py)', () => {
  it('speaks the schema version the app expects', () => {
    expect(menuSchema.properties.schema).toEqual({ const: ACTION_SCHEMA });
    expect(doctorSchema.properties.schema).toEqual({ const: ACTION_SCHEMA });
  });

  it("validates the engine's real menu and doctor output", () => {
    expect(validateMenu(menuGolden())).toEqual([]);
    expect(validateDoctor(doctorGolden())).toEqual([]);
  });

  it('rejects an unknown key and a wrong type — what drift looks like', () => {
    const menu = menuGolden<{ suggestions: Record<string, unknown>[] }>();
    menu.suggestions[0].surprise = 1;
    expect(validateMenu(menu)).not.toEqual([]);
    const doctor = doctorGolden<{ checks: Record<string, unknown>[] }>();
    doctor.checks[0].severity = 3;
    expect(validateDoctor(doctor)).not.toEqual([]);
  });

  it("parses the engine's real output without dropping a suggestion, a tool or an issue", () => {
    const rawMenu = menuGolden<{ suggestions: unknown[]; tools: unknown[] }>();
    const menu = parseMenu(JSON.stringify(rawMenu));
    expect(menu.suggestions).toHaveLength(rawMenu.suggestions.length);
    expect(menu.tools).toHaveLength(rawMenu.tools.length);

    const rawDoctor = doctorGolden<{ checks: { id: string; severity: string }[] }>();
    const doctor = parseDoctor(JSON.stringify(rawDoctor));
    const actionable = rawDoctor.checks.filter(
      (c) => (c.severity === 'critical' || c.severity === 'warning') && c.id !== 'engine-update-available',
    );
    expect(doctor.checks.map((c) => c.id)).toEqual(actionable.map((c) => c.id));
  });

  it('knows every field the engine sends', () => {
    expect(fieldInventoryDrift(KNOWN_FIELDS)).toEqual([]);
  });

  it('notices a field the engine adds', () => {
    const grown = structuredClone(menuSchema);
    grown.$defs.SuggestionJSON.properties.badge = { type: 'string' };
    expect(fieldInventoryDrift(KNOWN_FIELDS, [grown, doctorSchema])).toEqual([
      'SuggestionJSON: the schema has a field the app does not know: badge',
    ]);
  });
});
